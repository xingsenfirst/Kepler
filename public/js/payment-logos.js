/** 按平台 id 取元数据 */
export function paymentMeta(id) {
  return PAYMENT_META[id] || null;
}

/** 平台显示名 */
export function paymentName(id) {
  const m = paymentMeta(id);
  return m ? m.name : id;
}

/** 平台列表（按界面顺序） */
export function paymentList() {
  return ORDER.map((id) => PAYMENT_META[id]);
}

/** 生成平台图形 SVG */
export function paymentLogoSvg(id) {
  const s = SHAPES[id];
  if (!s) return '';
  const paths = s.paths.map((p) => `<path d="${p.d}" fill="${p.fill}"/>`).join('');
  return `<svg viewBox="${s.viewBox}" preserveAspectRatio="xMidYMid meet" aria-hidden="true">${paths}</svg>`;
}

